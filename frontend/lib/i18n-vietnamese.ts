const MIXED_JARGON = new RegExp(
  TECHNICAL_RULES.map(([pattern]) => pattern.source).join("|"),
  "i",
);

export function normalizeVietnameseUiText(source: string): string {
  const normalized = source.replace(/\s+/g, " ").trim();
  const exact = EXACT_VI[normalized];
  let localized = exact;
  if (localized === undefined) {
    if (!MIXED_JARGON.test(normalized)) localized = source;
    else {
      localized = normalized;
      for (const [pattern, replacement] of TECHNICAL_RULES) {
        localized = localized.replace(pattern, replacement);
      }
    }
  }

  return localized.replace(
    /điểm giao(?! hàng)/giu,
    (match) => match.startsWith("Đ") ? "Điểm giao hàng" : "điểm giao hàng",
  );
}
